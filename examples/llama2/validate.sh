#!/usr/bin/env bash
# Numerical parity of llama2.zero vs karpathy/llama2.c across every locally-
# available cross-platform branch.
#
# Two parity matrices run per branch:
#
#   * f32  -- against `run.c` on the real stories15M checkpoint. Gated: the run
#             passes only if every f32 case is byte-identical.
#   * int8 -- against `runq.c` (the "version 2" quantized format) on the
#             stories15M_q80.bin checkpoint, when that file is present. The same
#             Zero binary and CLI flags drive both checkpoints; the int8 format
#             is auto-detected by its magic number, no flag needed. The int8
#             matrix is informational (see note below), so it never affects the
#             run's exit code, and it self-skips when the int8 checkpoint is
#             absent.
#
# Builds the Zero example, fetches + builds the C reference, runs both on the
# real checkpoint, and diffs the generated token streams. At temperature 0
# (greedy argmax) the streams must be byte-identical; with temperature > 0 they
# must also match once the seed (12345) and sampler are aligned, because the
# xorshift* PRNG is reproduced bit-for-bit. Both sampler paths are checked:
# plain multinomial (`-p 0`) and top-p nucleus (`-p <0..1>`) each reproduce
# `llama2.c` token-for-token.
#
# The int8 path is validated for output quality but is not held to byte-for-byte
# token parity: its matmul rescales an exact int32 dot product back to f32 once
# per group, and that final floating-point accumulation differs by about one ULP
# between Zero's scalar code generation and an optimizing C compiler's vectorized
# reduction. At temperature 0 this occasionally flips a near-tied argmax; with
# temperature > 0 the multinomial/top-p sampler amplifies it. This is a property
# of int8 quantization on two different code generators, not a defect -- the f32
# path stays byte-for-byte identical to llama2.c on every platform. The int8
# matrix therefore runs informationally and reports OK / INFO(diverged) per case.
#
# Both sides expand raw-byte `<0xNN>` fallback tokens to the actual byte (e.g.
# `<0x0A>` -> a newline), so the generated byte streams are directly comparable.
#
# Both binaries must link the *same* libm, or token-for-token parity is
# impossible: every libm's expf/sinf/cosf/powf/sqrtf differ by ~1 ULP. So the C
# reference is always compiled with the *same toolchain and triple* as the Zero
# exe under test. This gives parity **per platform**, not byte-identity across
# platforms.
#
# Branches:
#
#   * native (Apple Silicon, no Docker)
#       Zero exe: Mach-O arm64, --backend zero-macho64, --target darwin-arm64
#       C ref:    zig cc -target aarch64-macos (macOS libSystem libm)
#       Run:      directly on the host
#       Probe:    darwin/arm64 host
#
#   * docker-amd64 (Linux/x64 CI gate)
#       Zero exe: static linux-musl-x64 ELF, --backend zero-elf64
#       C ref:    zig cc -target x86_64-linux-musl (zig's bundled musl libm)
#       Run:      inside an amd64 Alpine container (under qemu on non-x64 hosts)
#       Probe:    docker present
#
#   * docker-arm64 (linux-arm64 cross-platform)
#       Zero exe: static linux-musl-arm64 ELF, --backend zero-elf-aarch64
#       C ref:    zig cc -target aarch64-linux-musl
#       Run:      inside a linux/arm64 Alpine container (native on Apple Silicon, qemu elsewhere)
#       Probe:    docker can run linux/arm64 natively (no qemu) OR LLAMA2_BRANCHES forces it
#
#   * rosetta (darwin-x64 cross-platform via Rosetta)
#       Zero exe: Mach-O x86_64, --backend zero-macho-x64, --target darwin-x64
#       C ref:    zig cc -target x86_64-macos (macOS libSystem libm)
#       Run:      natively under Rosetta 2 on Apple Silicon (transparent translation)
#       Probe:    darwin/arm64 host + Rosetta available
#
# Selection (in priority order):
#   1. LLAMA2_BRANCHES=<csv>     explicit, comma-separated, e.g. "native,rosetta"
#   2. LLAMA2_FORCE_DOCKER=1     legacy alias for "docker-amd64"
#   3. auto (default)            picks every fast branch available on the host:
#                                  Apple Silicon:  native + docker-arm64 (if docker) + rosetta (if Rosetta)
#                                  Linux/x64:      docker-amd64
#                                  other:          docker-amd64 (if docker; slow under qemu) else error
#
# Each selected branch is run sequentially through the full f32 parity matrix --
# 11 cases (5 distinct prompts) across 3 sampling modes: 5 greedy-argmax + 3
# multinomial (temperature > 0) + 3 top-p (nucleus) -- then, when the int8
# checkpoint is present, the matching 11-case int8 matrix informationally. The
# script exits 0 only if every selected branch's f32 matrix passes.
#
# Override the data/cache dir with LLAMA2_DATA.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
data="${LLAMA2_DATA:-$root/.zero/llama2-data}"
zero="$root/bin/zero"
img="alpine"

model_url="https://huggingface.co/karpathy/tinyllamas/resolve/main/stories15M.bin"
tok_url="https://github.com/karpathy/llama2.c/raw/master/tokenizer.bin"
runc_url="https://github.com/karpathy/llama2.c/raw/master/run.c"
runqc_url="https://github.com/karpathy/llama2.c/raw/master/runq.c"
# The int8 v2 checkpoint is a one-time `export.py --version 2` export (PyTorch +
# the .pt weights), not a plain download. When absent the int8 matrix self-skips.
model_q="stories15M_q80.bin"

command -v zig >/dev/null 2>&1 || { echo "error: zig is required (builds the C reference against the same libm the Zero exe links)." >&2; exit 1; }
[ -x "$zero" ] || { echo "error: $zero not built. Run: make -C native/zero-c" >&2; exit 1; }

# Per-branch state. Each `branch_<name>` function sets these globals; the parity
# helpers read them, so the matrix code itself stays branch-agnostic.
branch_name=""
branch_label=""
zero_target=""           # zig cc triple
zero_compiler_target=""  # zero --target name
zero_backend=""          # zero --backend name (forced explicit so the parity check exercises the direct-exe path)
branch_zero_bin=""       # absolute path to built Zero exe
branch_ref_bin=""        # filename of built f32 C ref (run.c, relative to $data)
branch_runq_ref=""       # filename of built int8 C ref (runq.c, relative to $data)
branch_runner=""         # name of the runner function (run_native / run_docker_amd64 / run_docker_arm64 / run_rosetta)

# Runner functions: each receives two shell snippets (the Zero command and the
# C ref command, each writing its stdout to a per-branch txt file). They run
# both snippets in one inner shell (no set -e) so a failure in either still
# lets the other complete and the cmp catches divergences.
run_native()       { ( cd "$data" && sh -c "$1
$2" ); }
run_docker_amd64() { docker run --rm --platform linux/amd64 -v "$data":/work -w /work "$img" sh -c "$1
$2"; }
run_docker_arm64() { docker run --rm --platform linux/arm64 -v "$data":/work -w /work "$img" sh -c "$1
$2"; }
# Mach-O x86_64 binaries run transparently under Rosetta 2 on Apple Silicon.
# `arch -x86_64 sh` forces the inner shell into the x86_64 process tree so any
# subshell tooling stays consistent; the binaries themselves invoke Rosetta automatically.
run_rosetta()      { ( cd "$data" && arch -x86_64 sh -c "$1
$2" ); }

# Branch selectors. Each sets the per-branch globals; build_zero / build_ref /
# the parity helpers don't care which branch they're under.
branch_native() {
  branch_name="native"
  branch_label="darwin-arm64 native (Mach-O arm64, macOS libSystem libm)"
  zero_target="aarch64-macos"
  zero_compiler_target="darwin-arm64"
  zero_backend="zero-macho64"
  branch_zero_bin="$data/llama2-native"
  branch_ref_bin="run_ref-native"
  branch_runq_ref="runq_ref-native"
  branch_runner="run_native"
}
branch_docker_amd64() {
  branch_name="docker-amd64"
  branch_label="linux-musl-x64 Docker amd64 (musl libm)"
  zero_target="x86_64-linux-musl"
  zero_compiler_target="linux-musl-x64"
  zero_backend="zero-elf64"
  branch_zero_bin="$data/llama2-docker-amd64"
  branch_ref_bin="run_ref-docker-amd64"
  branch_runq_ref="runq_ref-docker-amd64"
  branch_runner="run_docker_amd64"
}
branch_docker_arm64() {
  branch_name="docker-arm64"
  branch_label="linux-musl-arm64 Docker arm64 (musl libm)"
  zero_target="aarch64-linux-musl"
  zero_compiler_target="linux-musl-arm64"
  zero_backend="zero-elf-aarch64"
  branch_zero_bin="$data/llama2-docker-arm64"
  branch_ref_bin="run_ref-docker-arm64"
  branch_runq_ref="runq_ref-docker-arm64"
  branch_runner="run_docker_arm64"
}
branch_rosetta() {
  branch_name="rosetta"
  branch_label="darwin-x64 Rosetta (Mach-O x86_64, macOS libSystem libm)"
  zero_target="x86_64-macos"
  zero_compiler_target="darwin-x64"
  zero_backend="zero-macho-x64"
  branch_zero_bin="$data/llama2-rosetta"
  branch_ref_bin="run_ref-rosetta"
  branch_runq_ref="runq_ref-rosetta"
  branch_runner="run_rosetta"
}

# Build a C reference (run.c) with the SAME toolchain the Zero exe links --
# zig cc cross/native-compiling to $zero_target -- so both sides share one libm.
# Building it with a different libm (e.g. the container's Alpine gcc/musl) skews
# libm (its expf etc. differ by ~1 ULP) and breaks token-for-token parity. Reuses
# Zero's own zig cache dirs.
#
# `-ffp-contract=off` matches the Zero backend's scalar FP, which emits a separate
# multiply then add (two roundings) and never a fused multiply-add. On arm64,
# `zig cc -O3` would otherwise contract `a*b+c` into a single `fmadd` (one
# rounding) -- a sub-ULP difference per multiply-accumulate, which the wide-margin
# f32 path absorbs but matters if the int8 path is ever revived. On x86-64 it is
# a no-op (SSE2 scalar does not auto-contract).
build_ref() { # build_ref <src.c> <out-basename> [extra cc flags...]
  src="$1"; out="$2"; shift 2
  ZIG_GLOBAL_CACHE_DIR="$root/.zero/zig-global-cache" \
  ZIG_LOCAL_CACHE_DIR="$root/.zero/zig-local-cache" \
    zig cc -target "$zero_target" -O3 -ffp-contract=off "$@" -o "$data/$out" "$data/$src"
}

# Build the Zero example for the current branch. For the Rosetta branch this
# requires ZERO_SYSROOT_X86_64_MACOS; auto-discover it when not set (mirrors
# the conformance harness's Docker probe).
build_zero() {
  if [ "$zero_compiler_target" = "darwin-x64" ] && [ -z "${ZERO_SYSROOT_X86_64_MACOS:-}" ]; then
    if command -v xcrun >/dev/null 2>&1; then
      export ZERO_SYSROOT_X86_64_MACOS="$(xcrun --show-sdk-path)"
    fi
  fi
  "$zero" build --backend "$zero_backend" --emit exe --target "$zero_compiler_target" "$root/examples/llama2" --out "$branch_zero_bin" >/dev/null
}

# Both sides now expand raw-byte <0xNN> tokens to the actual byte, so the streams
# are directly byte-comparable.
norm_and_diff() {
  if cmp -s "$1" "$2"; then
    return 0
  fi
  echo "--- llama2.zero" >&2
  cat "$1" >&2
  echo "--- llama2.c" >&2
  cat "$2" >&2
  return 1
}

# parity_one <temperature> <tokens> <prompt>
parity_one() {
  t="$1"; n="$2"; p="$3"
  if [ "$t" = "0" ]; then ref_extra=""; else ref_extra="-p 0 -s 12345"; fi
  # Capture the Zero exe's stderr to a per-branch file so a FAIL can show its
  # `error: ...` message instead of swallowing it. The C ref's stderr stays muted.
  $branch_runner \
    "./llama2-$branch_name stories15M.bin --prompt '$p' --tokens $n --temperature $t 2>ze-$branch_name.txt > z-$branch_name.txt" \
    "./$branch_ref_bin stories15M.bin -z tokenizer.bin -t $t $ref_extra -n $n -i '$p' 2>/dev/null > r-$branch_name.txt"
  if norm_and_diff "$data/z-$branch_name.txt" "$data/r-$branch_name.txt"; then
    echo "  OK   [t=$t, $n tok] \"$p\""
  else
    echo "  FAIL [t=$t, $n tok] \"$p\""
    [ -s "$data/ze-$branch_name.txt" ] && { echo "  --- llama2.zero stderr" >&2; cat "$data/ze-$branch_name.txt" >&2; }
    return 1
  fi
}

# parity_topp <temperature> <tokens> <topp> <prompt> -- top-p (nucleus) path. The
# reference gets a real `-p <topp>` (not `-p 0`) plus the matched seed; the Zero
# side gets `--topp <topp>`. Same xorshift* PRNG + same sample_topp => identical
# streams.
parity_topp() {
  t="$1"; n="$2"; pp="$3"; p="$4"
  $branch_runner \
    "./llama2-$branch_name stories15M.bin --prompt '$p' --tokens $n --temperature $t --topp $pp 2>ze-$branch_name.txt > z-$branch_name.txt" \
    "./$branch_ref_bin stories15M.bin -z tokenizer.bin -t $t -p $pp -s 12345 -n $n -i '$p' 2>/dev/null > r-$branch_name.txt"
  if norm_and_diff "$data/z-$branch_name.txt" "$data/r-$branch_name.txt"; then
    echo "  OK   [t=$t, p=$pp, $n tok] \"$p\""
  else
    echo "  FAIL [t=$t, p=$pp, $n tok] \"$p\""
    [ -s "$data/ze-$branch_name.txt" ] && { echo "  --- llama2.zero stderr" >&2; cat "$data/ze-$branch_name.txt" >&2; }
    return 1
  fi
}

# parity_one_q <temperature> <tokens> <prompt> -- int8 analogue of parity_one.
# Drives the SAME Zero exe pointed at "$model_q" (auto-detects the v2 magic, no
# flag) and the int8 C reference "$branch_runq_ref" (runq.c). Informational: it
# prints OK / INFO(diverged) and always returns 0, so an int8 divergence never
# fails the run (see header note on int8 reduction-order noise).
parity_one_q() {
  t="$1"; n="$2"; p="$3"
  if [ "$t" = "0" ]; then ref_extra=""; else ref_extra="-p 0 -s 12345"; fi
  $branch_runner \
    "./llama2-$branch_name $model_q --prompt '$p' --tokens $n --temperature $t 2>zqe-$branch_name.txt > zq-$branch_name.txt" \
    "./$branch_runq_ref $model_q -z tokenizer.bin -t $t $ref_extra -n $n -i '$p' 2>/dev/null > rq-$branch_name.txt"
  if cmp -s "$data/zq-$branch_name.txt" "$data/rq-$branch_name.txt"; then
    echo "  OK            [q, t=$t, $n tok] \"$p\""
  else
    echo "  INFO(diverged) [q, t=$t, $n tok] \"$p\""
    [ -s "$data/zqe-$branch_name.txt" ] && { echo "  --- llama2.zero stderr" >&2; cat "$data/zqe-$branch_name.txt" >&2; }
  fi
  return 0
}

# parity_topp_q <temperature> <tokens> <topp> <prompt> -- int8 analogue of
# parity_topp. Informational, same conventions as parity_one_q.
parity_topp_q() {
  t="$1"; n="$2"; pp="$3"; p="$4"
  $branch_runner \
    "./llama2-$branch_name $model_q --prompt '$p' --tokens $n --temperature $t --topp $pp 2>zqe-$branch_name.txt > zq-$branch_name.txt" \
    "./$branch_runq_ref $model_q -z tokenizer.bin -t $t -p $pp -s 12345 -n $n -i '$p' 2>/dev/null > rq-$branch_name.txt"
  if cmp -s "$data/zq-$branch_name.txt" "$data/rq-$branch_name.txt"; then
    echo "  OK            [q, t=$t, p=$pp, $n tok] \"$p\""
  else
    echo "  INFO(diverged) [q, t=$t, p=$pp, $n tok] \"$p\""
    [ -s "$data/zqe-$branch_name.txt" ] && { echo "  --- llama2.zero stderr" >&2; cat "$data/zqe-$branch_name.txt" >&2; }
  fi
  return 0
}

# Probe helpers: each prints "ok" on stdout if the branch can run on this host,
# otherwise nothing. Used by the `auto` selector and by explicit-branch sanity
# checks. The probes are cheap (no llama2 build, no full container spin-up).
probe_native() {
  [ "$(uname -s)" = "Darwin" ] && [ "$(uname -m)" = "arm64" ] && echo ok || true
}
probe_docker() {
  command -v docker >/dev/null 2>&1 && echo ok || true
}
# linux-arm64 docker is fast only when the host is natively arm64 (Apple Silicon
# or arm64 Linux); otherwise it runs under qemu, which is hours-slow for llama2.
# Probe: actually start a tiny linux/arm64 container and verify `uname -m`.
probe_docker_arm64_native() {
  command -v docker >/dev/null 2>&1 || return
  if [ "$(docker run --rm --platform linux/arm64 alpine uname -m 2>/dev/null)" = "aarch64" ]; then
    # Native iff the host kernel also reports an arm64 machine; otherwise qemu is in play.
    case "$(uname -m)" in
      arm64|aarch64) echo ok ;;
    esac
  fi
}
probe_rosetta() {
  [ "$(uname -s)" = "Darwin" ] && [ "$(uname -m)" = "arm64" ] || return
  arch -x86_64 true 2>/dev/null && echo ok || true
}

# Run a single branch end-to-end: build Zero + ref, then the parity matrix.
# Returns 0 only if all 11 parities pass.
run_branch_matrix() {
  echo ""
  echo "==> $branch_label"
  echo "==> building llama2.zero (--backend $zero_backend, --target $zero_compiler_target)"
  build_zero
  echo "==> building llama2.c reference (zig cc -> $zero_target, matching the Zero exe)"
  # run.c relies on transitive stdint.h (glibc); musl/libSystem need it forced.
  build_ref run.c "$branch_ref_bin" -include stdint.h

  fail=0
  echo "==> temperature 0 (deterministic argmax) parity"
  parity_one 0 100 "Once upon a time" || fail=1
  parity_one 0 120 "Lily and Tom went to the park" || fail=1
  parity_one 0 80  "The little robot" || fail=1
  parity_one 0 256 "One day" || fail=1
  parity_one 0 60  "" || fail=1

  echo "==> temperature > 0 (softmax + xorshift* PRNG + multinomial) parity"
  parity_one 0.8 100 "Once upon a time" || fail=1
  parity_one 1.0 100 "The dragon" || fail=1
  parity_one 0.5 80  "" || fail=1

  echo "==> temperature > 0 with top-p (nucleus) parity"
  parity_topp 0.8 100 0.9  "Once upon a time" || fail=1
  parity_topp 1.0 100 0.95 "The dragon" || fail=1
  parity_topp 0.9 80  0.9  "" || fail=1

  # ---- int8 (runq.c "version 2") matrix -- informational, never gating -------
  # Self-skips when the int8 checkpoint is absent (keeps the f32 matrix
  # dependency-free). When present it builds the int8 C reference with the SAME
  # toolchain/triple as the f32 one and runs the same prompt set; divergences are
  # logged as INFO and never set `fail` (see header note).
  if [ -f "$data/$model_q" ]; then
    quant_ran=1
    echo "==> building llama2.c int8 reference (runq.c, zig cc -> $zero_target)"
    [ -f "$data/runq.c" ] || curl -fSL -o "$data/runq.c" "$runqc_url"
    # runq.c already includes <stdint.h>; build_ref applies -ffp-contract=off + -target.
    build_ref runq.c "$branch_runq_ref"

    echo "==> int8 temperature 0 (deterministic argmax) -- informational"
    parity_one_q 0 100 "Once upon a time"
    parity_one_q 0 120 "Lily and Tom went to the park"
    parity_one_q 0 80  "The little robot"
    parity_one_q 0 256 "One day"
    parity_one_q 0 60  ""

    echo "==> int8 temperature > 0 (multinomial) -- informational"
    parity_one_q 0.8 100 "Once upon a time"
    parity_one_q 1.0 100 "The dragon"
    parity_one_q 0.5 80  ""

    echo "==> int8 temperature > 0 with top-p (nucleus) -- informational"
    parity_topp_q 0.8 100 0.9  "Once upon a time"
    parity_topp_q 1.0 100 0.95 "The dragon"
    parity_topp_q 0.9 80  0.9  ""
  else
    echo "==> int8 (runq.c v2) matrix: SKIP -- no $model_q in $data."
    echo "    The int8 checkpoint is a one-time \`export.py --version 2\` export"
    echo "    (needs PyTorch + the .pt weights), not a download. The f32 matrix"
    echo "    above is unaffected -- this is a skip, not a failure."
  fi

  return "$fail"
}

# ---- Branch selection ---------------------------------------------------

selected_branches=""
if [ -n "${LLAMA2_BRANCHES:-}" ]; then
  # Explicit list: trust the caller; runtime probe still catches missing tools.
  selected_branches="$(echo "$LLAMA2_BRANCHES" | tr ',' ' ')"
elif [ "${LLAMA2_FORCE_DOCKER:-0}" = "1" ]; then
  # Backward compat: the original two-branch script accepted this flag to override
  # the darwin-native default with the linux/amd64 container branch.
  selected_branches="docker-amd64"
else
  # Auto: pick every fast branch available on the host. Apple Silicon gets up to
  # three branches (native + docker-arm64 + rosetta) -- all run at near-native
  # speed, ~3-5 min each. Linux/x64 gets docker-amd64. Other hosts try docker-amd64
  # under qemu (slow) and warn.
  if [ -n "$(probe_native)" ]; then
    selected_branches="native"
    if [ -n "$(probe_docker_arm64_native)" ]; then
      selected_branches="$selected_branches docker-arm64"
    fi
    if [ -n "$(probe_rosetta)" ]; then
      selected_branches="$selected_branches rosetta"
    fi
  elif [ -n "$(probe_docker)" ]; then
    selected_branches="docker-amd64"
  else
    echo "error: no usable branches; need either a darwin/arm64 host (with zig) or Docker." >&2
    echo "       Set LLAMA2_BRANCHES=<branch1,branch2,...> to override." >&2
    exit 1
  fi
fi

# Verify each selected branch has its tooling. Soft-fail (skip with warning) on
# auto-selected branches; hard-fail when the user explicitly listed them.
sanity_check_branch() { # $1 = branch name
  case "$1" in
    native)       [ -n "$(probe_native)" ] && return 0 ; echo "warning: 'native' requires darwin/arm64 host" >&2 ;;
    docker-amd64) [ -n "$(probe_docker)" ] && return 0 ; echo "warning: 'docker-amd64' requires Docker" >&2 ;;
    docker-arm64) [ -n "$(probe_docker)" ] && return 0 ; echo "warning: 'docker-arm64' requires Docker" >&2 ;;
    rosetta)      [ -n "$(probe_rosetta)" ] && return 0 ; echo "warning: 'rosetta' requires darwin/arm64 host with Rosetta 2" >&2 ;;
    *)            echo "error: unknown branch '$1'; valid: native, docker-amd64, docker-arm64, rosetta" >&2; return 2 ;;
  esac
  return 1
}

# ---- Setup: fetch model + tokenizer + run.c -----------------------------

mkdir -p "$data"
echo "==> fetching weights + reference into $data"
# Reuse the repo-root checkpoint/tokenizer if present (avoids a redundant 60 MB
# download); fall back to fetching. A symlink keeps $data self-contained for the
# Docker bind-mounts and the native runs alike.
if [ ! -e "$data/stories15M.bin" ]; then
  if [ -f "$root/stories15M.bin" ]; then ln -s "$root/stories15M.bin" "$data/stories15M.bin"
  else curl -fSL -o "$data/stories15M.bin" "$model_url"; fi
fi
if [ ! -e "$data/tokenizer.bin" ]; then
  if [ -f "$root/tokenizer.bin" ]; then ln -s "$root/tokenizer.bin" "$data/tokenizer.bin"
  else curl -fSL -o "$data/tokenizer.bin" "$tok_url"; fi
fi
[ -f "$data/run.c" ] || curl -fSL -o "$data/run.c" "$runc_url"

# ---- Iterate every selected branch --------------------------------------

echo "==> selected branches: $selected_branches"

overall_fail=0
ran_branches=""
skipped_branches=""
quant_ran=0   # set by run_branch_matrix when the int8 matrix actually ran

for b in $selected_branches; do
  if ! sanity_check_branch "$b"; then
    rc=$?
    if [ "$rc" -eq 2 ] || [ -n "${LLAMA2_BRANCHES:-}" ]; then
      # Hard fail for unknown branch or explicit selection.
      overall_fail=1
      skipped_branches="$skipped_branches $b(unavailable)"
      continue
    fi
    # Auto-selected branch missing tools: skip with a warning rather than failing.
    skipped_branches="$skipped_branches $b(no-tooling)"
    continue
  fi

  case "$b" in
    native)       branch_native ;;
    docker-amd64) branch_docker_amd64 ;;
    docker-arm64) branch_docker_arm64 ;;
    rosetta)      branch_rosetta ;;
  esac

  if run_branch_matrix; then
    ran_branches="$ran_branches $b"
  else
    overall_fail=1
    ran_branches="$ran_branches $b(FAIL)"
  fi
done

echo ""
if [ "$overall_fail" -eq 0 ]; then
  echo "==> PASS: llama2.zero matches llama2.c token-for-token on stories15M (f32) across:$ran_branches"
  if [ "$quant_ran" -eq 1 ]; then
    echo "         int8: ran runq.c parity informationally on $model_q (see per-case OK / INFO(diverged) above)"
  else
    echo "         int8: NOTE -- $model_q absent, runq.c matrix skipped (one-time export.py --version 2 export)"
  fi
  if [ -n "$skipped_branches" ]; then
    echo "         skipped:$skipped_branches"
  fi
else
  echo "==> FAIL: divergence in one or more branches." >&2
  echo "          ran:$ran_branches" >&2
  if [ -n "$skipped_branches" ]; then
    echo "          skipped:$skipped_branches" >&2
  fi
  exit 1
fi
